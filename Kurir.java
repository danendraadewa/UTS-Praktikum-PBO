package UTS;

public class Kurir {

    private String nama;
    private String kendaraan;

    public Kurir(String nama, String kendaraan) {
        this.nama = nama;
        this.kendaraan = kendaraan;
    }

    public String getNama() {
        return nama;
    }

    public String getKendaraan() {
        return kendaraan;
    }
}
